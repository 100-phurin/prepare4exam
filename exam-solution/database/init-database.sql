DROP DATABASE IF EXISTS mobile_distributor;
CREATE DATABASE mobile_distributor CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE mobile_distributor;

CREATE TABLE brands (
  id INT PRIMARY KEY AUTO_INCREMENT,
  name VARCHAR(50) NOT NULL UNIQUE,
  country_of_origin VARCHAR(50),
  website VARCHAR(100),
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE products (
  id INT PRIMARY KEY AUTO_INCREMENT,
  sku VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  brand_id INT NOT NULL,
  category ENUM('FLAGSHIP','MID_RANGE','BUDGET') NOT NULL,
  price DECIMAL(10,2) NOT NULL,
  ram_gb INT,
  storage_gb INT,
  color VARCHAR(40),
  stock_quantity INT NOT NULL DEFAULT 0,
  status ENUM('AVAILABLE','OUT_OF_STOCK','DISCONTINUED') NOT NULL DEFAULT 'AVAILABLE',
  release_date DATE,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_products_brand FOREIGN KEY (brand_id) REFERENCES brands(id)
);

